-- View 8: v_public_attack_events
CREATE OR REPLACE VIEW v_public_attack_events AS
SELECT 
    event_id,
    run_id,
    window_id,
    timestamp_epoch,
    timestamp_utc,
    category,
    status,
    severity,
    confidence,
    CASE 
        WHEN source_mac IS NOT NULL THEN CONCAT(SUBSTRING(source_mac FROM 1 FOR 8), ':**:**:', SUBSTRING(source_mac FROM 16 FOR 2))
        ELSE NULL 
    END AS source_mac,
    CASE 
        WHEN target_ip IS NOT NULL THEN REGEXP_REPLACE(target_ip, '\.[0-9]+$', '.***')
        ELSE NULL 
    END AS target_ip,
    evidence_json,
    missing_fields_json,
    recommended_action,
    acknowledged,
    created_at
FROM live_attack_events;

-- View 9: v_public_traffic_overview (Fast Aggregated Overview for Header)
CREATE OR REPLACE VIEW v_public_traffic_overview AS
SELECT 
    w.run_id,
    COUNT(*) AS total_windows,
    COALESCE(SUM(w.packet_count), 0) AS total_packets,
    COUNT(*) FILTER (WHERE w.pred_dual = -1) AS anomaly_windows,
    COUNT(*) FILTER (WHERE w.pred_primary = -1) AS primary_flags,
    COUNT(*) FILTER (WHERE w.pred_timing = -1 AND w.timing_status = 'ACTIVE') AS timing_flags,
    ROUND((COUNT(*) FILTER (WHERE w.pred_dual = -1)::numeric / NULLIF(COUNT(*), 0) * 100.0), 2) AS anomaly_pct,
    COALESCE(AVG(w.packet_rate), 0.0) AS avg_rate,
    COALESCE(MAX(w.packet_rate), 0.0) AS peak_rate,
    MAX(w.window_start_utc) AS latest_window_utc
FROM live_traffic_windows w
GROUP BY w.run_id;

