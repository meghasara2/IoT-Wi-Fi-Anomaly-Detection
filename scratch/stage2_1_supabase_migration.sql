-- 3. SANITIZED PUBLIC VIEWS FOR STREAMLIT COMMUNITY CLOUD
-- -----------------------------------------------------------------------------
-- Anonymous dashboard visitors query these views ONLY.
-- Raw hardware MAC addresses, host adapter GUIDs, and exact client IPs are masked.

-- Helper masking logic:
-- MAC:  'ca:34:ea:92:d3:9e' -> 'ca:34:ea:**:**:9e' (OUI preserved, NIC masked)
-- IP:   '192.168.137.101'   -> '192.168.137.***' (Subnet preserved, host masked)
-- GUID: Internal Windows adapter strings -> 'Local_Hotspot_Virtual_AP'

-- View 1: v_public_collector_status
CREATE OR REPLACE VIEW v_public_collector_status AS
SELECT 
    run_id,
    started_at,
    last_heartbeat,
    ROUND(EXTRACT(EPOCH FROM (clock_timestamp() - last_heartbeat))::numeric, 1) AS heartbeat_age_seconds,
    CASE 
        WHEN last_heartbeat IS NULL THEN 'OFFLINE'
        WHEN EXTRACT(EPOCH FROM (clock_timestamp() - last_heartbeat)) <= 15.0 THEN 'LIVE'
        WHEN EXTRACT(EPOCH FROM (clock_timestamp() - last_heartbeat)) <= 60.0 THEN 'STALE'
        ELSE 'OFFLINE'
    END AS connection_state,
    CASE WHEN interface_name IS NOT NULL THEN 'Local_Hotspot_Virtual_AP' ELSE NULL END AS interface_name,
    CASE WHEN serial_port IS NOT NULL THEN 'ESP32_Serial_UART' ELSE NULL END AS serial_port,
    status,
    stop_reason,
    packets_parsed,
    windows_emitted,
    sensor_records
FROM collector_status;

-- View 2: v_public_device_registry
CREATE OR REPLACE VIEW v_public_device_registry AS
SELECT 
    CONCAT(SUBSTRING(mac_address FROM 1 FOR 8), ':**:**:', SUBSTRING(mac_address FROM 16 FOR 2)) AS client_mac,
    node_id,
    device_type,
    label,
    last_seen,
    CASE 
        WHEN notes ILIKE '%phone 1%' THEN 'Authorized Hotspot Client 1'
        WHEN notes ILIKE '%phone 2%' THEN 'Authorized Hotspot Client 2'
        WHEN notes ILIKE '%phone 3%' THEN 'Authorized Hotspot Client 3 (Reserved)'
        ELSE 'Registered Station'
    END AS notes
FROM device_registry;

-- View 3: v_public_live_traffic_windows
