    physical_node_id    TEXT NOT NULL DEFAULT 'esp32_gateway',
    logical_node_id     TEXT NOT NULL DEFAULT 'Node_2',
    sequence_num        INTEGER NOT NULL,
    uptime_ms           BIGINT NOT NULL,
    motion_detected     INTEGER NOT NULL,
