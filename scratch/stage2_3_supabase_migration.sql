-- View 8: v_public_attack_events (PATCHED: F-02 & F-03 Complete Sanitization)
CREATE OR REPLACE VIEW v_public_attack_events AS
SELECT 
    event_id,
    event_uuid,
    run_id,
    window_id,
    timestamp_epoch,
    timestamp_utc,
    category,
    status,
    severity,
    confidence,
    CASE 
        WHEN source_mac IS NOT NULL THEN CONCAT('ATTACKER-', UPPER(SUBSTRING(MD5(source_mac || 'iot_guard_salt_2026') FROM 1 FOR 6)))
        ELSE NULL 
    END AS source_station_id,
    CASE 
        WHEN target_ip IS NOT NULL THEN '192.168.137.***'
        ELSE NULL 
    END AS target_ip,
    
    -- F-02 Sanitized Evidence: Strips raw MACs, IPs, and nested detail dictionaries
    jsonb_strip_nulls(jsonb_build_object(
        'verdict', evidence_json->>'verdict',
        'destination_scope', CASE 
            WHEN evidence_json->>'destination_scope' ILIKE '%LAN%' THEN 'Local LAN Subnet'
            WHEN evidence_json->>'destination_scope' ILIKE '%WAN%' THEN 'WAN / Internet'
            ELSE 'Network Scope'
        END,
        'probe_counts', (evidence_json->>'probe_counts')::int,
        'distinct_ports_count', (evidence_json->>'distinct_ports_count')::int,
        'distinct_hosts_count', (evidence_json->>'distinct_hosts_count')::int,
        'tcp_syn_count', (evidence_json->>'tcp_syn_count')::int,
        'udp_probe_count', (evidence_json->>'udp_probe_count')::int,
        'current_rate_pps', (evidence_json->>'current_rate_pps')::float,
        'rate_threshold_pps', (evidence_json->>'rate_threshold_pps')::float,
        'consecutive_windows', (evidence_json->>'consecutive_windows')::int,
        'target_concentration', (evidence_json->>'target_concentration')::float,
        'is_vertical_scan', (evidence_json->>'is_vertical_scan')::boolean,
        'is_horizontal_sweep', (evidence_json->>'is_horizontal_sweep')::boolean,
        'total_mgmt_frames', (evidence_json->>'total_mgmt_frames')::int,
        'deauth_count', (evidence_json->>'deauth_count')::int,
        'reason', evidence_json->>'reason',
        'initial_capability', evidence_json->>'initial_capability',
        'limitations_or_remedy', evidence_json->>'limitations_or_remedy'
    )) AS sanitized_evidence_json,
    
    missing_fields_json,
    
    -- F-02 Action Sanitization: Regex masks any MAC or IP mentioned in recommendation prose
    REGEXP_REPLACE(
        REGEXP_REPLACE(
            recommended_action,
            '([0-9a-fA-F]{2}[:-]){5}[0-9a-fA-F]{2}',
            'PROTECTED_MAC',
            'g'
        ),
        '\m[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\M',
        'PROTECTED_IP',
        'g'
    ) AS recommended_action,
    
    acknowledged,
    created_at
FROM live_attack_events;

-- View 9: v_public_traffic_overview (Fast Aggregated Overview for Header)
CREATE OR REPLACE VIEW v_public_traffic_overview AS
SELECT 
    w.run_id,
    COUNT(*) AS total_windows,
    COALESCE(SUM(w.packet_count), 0) AS total_packets,
    COUNT(*) FILTER (WHERE w.pred_dual = -1) AS anomaly_windows,
    COUNT(*) FILTER (WHERE w.pred_primary = -1) AS primary_flags,
    COUNT(*) FILTER (WHERE w.pred_timing = -1 AND w.timing_status = 'ACTIVE') AS timing_flags,
    ROUND((COUNT(*) FILTER (WHERE w.pred_dual = -1)::numeric / NULLIF(COUNT(*), 0) * 100.0), 2) AS anomaly_pct,
    COALESCE(AVG(w.packet_rate), 0.0) AS avg_rate,
    COALESCE(MAX(w.packet_rate), 0.0) AS peak_rate,
    MAX(w.window_start_utc) AS latest_window_utc
FROM live_traffic_windows w
GROUP BY w.run_id;

