-- -----------------------------------------------------------------------------
-- 8. LIVE ATTACK DETECTION EVENTS
-- -----------------------------------------------------------------------------
-- Deterministic cyberattack evaluations from NetworkAttackDetector engine.
CREATE TABLE IF NOT EXISTS live_attack_events (
    event_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id              BIGINT NOT NULL REFERENCES collector_status(run_id) ON DELETE CASCADE,
    window_id           BIGINT REFERENCES live_traffic_windows(window_id) ON DELETE SET NULL,
    timestamp_epoch     DOUBLE PRECISION NOT NULL,
    timestamp_utc       TIMESTAMPTZ NOT NULL,
    category            TEXT NOT NULL,
        CONSTRAINT chk_attack_category CHECK (category IN (
            'Denial_of_Service',
            'Reconnaissance_Port_Scan',
            'Spoofing_Impersonation',
            'Deauthentication_Disassociation_Abuse',
            'Replay_Attack'
        )),
    status              TEXT NOT NULL,
        CONSTRAINT chk_attack_status CHECK (status IN (
            'NO_EVIDENCE',
            'INSUFFICIENT_TELEMETRY',
            'SUSPICIOUS',
            'CONFIRMED_THREAT'
        )),
    severity            TEXT NOT NULL,
        CONSTRAINT chk_attack_severity CHECK (severity IN (
            'NONE',
            'INFO',
            'LOW',
            'MEDIUM',
            'HIGH',
            'CRITICAL'
        )),
    confidence          DOUBLE PRECISION NOT NULL,
        CONSTRAINT chk_confidence_range CHECK (confidence >= 0.0 AND confidence <= 1.0),
    source_mac          TEXT,
    target_ip           TEXT,
    evidence_json       JSONB NOT NULL DEFAULT '{}'::jsonb,
    missing_fields_json JSONB DEFAULT '[]'::jsonb,
    recommended_action  TEXT,
    acknowledged        INTEGER NOT NULL DEFAULT 0,
        CONSTRAINT chk_attack_ack CHECK (acknowledged IN (0, 1)),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    
    -- Idempotency constraint: Unique per run, epoch timestamp, and attack category
    CONSTRAINT uq_attack_event UNIQUE (run_id, timestamp_epoch, category)
);

COMMENT ON TABLE live_attack_events IS 'Explainable deterministic cyberattack events evaluated by NetworkAttackDetector.';

CREATE INDEX IF NOT EXISTS idx_attack_run_cat 
    ON live_attack_events(run_id, category, status);
CREATE INDEX IF NOT EXISTS idx_attack_timestamp 
    ON live_attack_events(timestamp_epoch DESC);
CREATE INDEX IF NOT EXISTS idx_attack_severity 
    ON live_attack_events(run_id, severity) WHERE severity IN ('HIGH', 'CRITICAL');

