-- IoT Network Guard — Dual-Detector SOC Console
-- Stage 2: Supabase PostgreSQL Schema Migration & Security Blueprint
-- File: scratch/stage2_supabase_migration.sql
-- 
-- Target Platform: Supabase Managed PostgreSQL
-- Compatible with: PostgreSQL 14, 15, 16+
-- Schema Version: 2.0.0 (Cloud Live Monitoring Baseline)
-- 
-- Design Principles:
--   1. Full parity with local SQLite 8-table schema (src/init_live_database.py).
--   2. Strict Row-Level Security (RLS) on all tables.
--   3. Asymmetric privilege model:
--      - anon role: Read-only (SELECT) for Streamlit Community Cloud.
--      - collector / service_role: Write-only (INSERT, UPDATE) for local collector.
--      - NO DELETE permissions granted to any ingestion role.
--   4. Idempotent design: Natural unique constraints for safe re-transmissions.
--   5. High-performance indexing for real-time SOC queries (< 100ms response).
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 0. EXTENSIONS & PRAGMAS
-- -----------------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- Set client timezone to UTC for absolute timestamp precision
SET timezone = 'UTC';

-- -----------------------------------------------------------------------------
-- 1. COLLECTOR STATUS & HEARTBEAT TABLE
-- -----------------------------------------------------------------------------
-- Tracks live daemon execution lifecycles and provides the real-time heartbeat
-- that drives the dashboard's LIVE (<15s) / STALE (15-60s) / OFFLINE (>60s) state.
CREATE TABLE IF NOT EXISTS collector_status (
    run_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    last_heartbeat      TIMESTAMPTZ,
    interface_index     INTEGER,
    interface_name      TEXT,
    serial_port         TEXT,
    status              TEXT NOT NULL DEFAULT 'STARTING',
        CONSTRAINT chk_collector_status CHECK (status IN ('STARTING', 'RUNNING', 'STOPPED', 'ERROR')),
    stop_reason         TEXT,
    packets_parsed      BIGINT NOT NULL DEFAULT 0,
    windows_emitted     BIGINT NOT NULL DEFAULT 0,
    sensor_records      BIGINT NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

COMMENT ON TABLE collector_status IS 'Daemon lifecycle and heartbeat telemetry emitted by local LiveCollector.';
COMMENT ON COLUMN collector_status.run_id IS 'Unique identifier for each collector execution session.';
COMMENT ON COLUMN collector_status.status IS 'Current operational status: STARTING, RUNNING, STOPPED, ERROR.';

-- Indexes for status
CREATE INDEX IF NOT EXISTS idx_collector_status_heartbeat 
    ON collector_status(last_heartbeat DESC);
CREATE INDEX IF NOT EXISTS idx_collector_status_run_desc 
    ON collector_status(run_id DESC);

-- -----------------------------------------------------------------------------
-- 2. DEVICE REGISTRY TABLE
-- -----------------------------------------------------------------------------
-- Curated inventory of authorized network clients (Node_3, Node_4, Node_5).
CREATE TABLE IF NOT EXISTS device_registry (
    mac_address         TEXT PRIMARY KEY,
        CONSTRAINT chk_mac_format CHECK (mac_address ~* '^([0-9a-f]{2}[:-]){5}([0-9a-f]{2})$'),
    node_id             TEXT NOT NULL,
    device_type         TEXT NOT NULL DEFAULT 'Phone_Client',
    label               TEXT NOT NULL DEFAULT 'real_observed_traffic',
    last_seen           TIMESTAMPTZ,
    notes               TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

COMMENT ON TABLE device_registry IS 'Curated inventory of registered Wi-Fi client stations.';

CREATE INDEX IF NOT EXISTS idx_device_registry_node 
    ON device_registry(node_id);

-- -----------------------------------------------------------------------------
-- 3. LIVE TRAFFIC WINDOWS TABLE
-- -----------------------------------------------------------------------------
-- Aggregated 1-second feature windows per node, scored by the Dual Isolation Forest.
CREATE TABLE IF NOT EXISTS live_traffic_windows (
    window_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id              BIGINT NOT NULL REFERENCES collector_status(run_id) ON DELETE CASCADE,
    client_mac          TEXT NOT NULL,
    node_id             TEXT NOT NULL,
    node_type           TEXT,
    data_label          TEXT,
    bin_start_epoch     DOUBLE PRECISION NOT NULL,
    bin_end_epoch       DOUBLE PRECISION NOT NULL,
    window_center_epoch DOUBLE PRECISION,
    window_start_utc    TIMESTAMPTZ,
    window_end_utc      TIMESTAMPTZ,
    packet_count        INTEGER NOT NULL DEFAULT 0,
    mean_IAT            DOUBLE PRECISION,
    IAT_std             DOUBLE PRECISION,
    packet_rate         DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    mean_packet_size    DOUBLE PRECISION,
    packet_size_std     DOUBLE PRECISION,
    score_primary       DOUBLE PRECISION,
    pred_primary        INTEGER,
        CONSTRAINT chk_pred_primary CHECK (pred_primary IN (-1, 1) OR pred_primary IS NULL),
    score_timing        DOUBLE PRECISION,
    pred_timing         INTEGER,
        CONSTRAINT chk_pred_timing CHECK (pred_timing IN (-1, 1) OR pred_timing IS NULL),
    timing_status       TEXT,
        CONSTRAINT chk_timing_status CHECK (timing_status IN ('ACTIVE', 'UNAVAILABLE_N_LT_3') OR timing_status IS NULL),
    pred_dual           INTEGER,
        CONSTRAINT chk_pred_dual CHECK (pred_dual IN (-1, 1) OR pred_dual IS NULL),
    dual_reason         TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    
    -- Idempotency constraint: A node can only have one window per start epoch per run
    CONSTRAINT uq_traffic_window_run_mac_epoch UNIQUE (run_id, client_mac, bin_start_epoch)
);

COMMENT ON TABLE live_traffic_windows IS '1-second statistical feature windows scored by Dual Isolation Forest.';

-- High-performance query indexes
CREATE INDEX IF NOT EXISTS idx_ltw_run_node 
    ON live_traffic_windows(run_id, node_id);
CREATE INDEX IF NOT EXISTS idx_ltw_bin_start 
    ON live_traffic_windows(bin_start_epoch DESC);
CREATE INDEX IF NOT EXISTS idx_ltw_run_bin_start 
    ON live_traffic_windows(run_id, bin_start_epoch DESC);
CREATE INDEX IF NOT EXISTS idx_ltw_pred_dual 
    ON live_traffic_windows(run_id, pred_dual) WHERE pred_dual = -1;

-- -----------------------------------------------------------------------------
-- 4. STATISTICAL ANOMALY ALERTS TABLE
-- -----------------------------------------------------------------------------
-- Flags windows where Dual Isolation Forest indicates statistical deviation.
CREATE TABLE IF NOT EXISTS live_alerts (
    alert_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    window_id           BIGINT NOT NULL REFERENCES live_traffic_windows(window_id) ON DELETE CASCADE,
    run_id              BIGINT NOT NULL REFERENCES collector_status(run_id) ON DELETE CASCADE,
    client_mac          TEXT NOT NULL,
    node_id             TEXT NOT NULL,
    bin_start_epoch     DOUBLE PRECISION NOT NULL,
    window_start_utc    TIMESTAMPTZ,
    dual_reason         TEXT NOT NULL,
    score_primary       DOUBLE PRECISION,
    score_timing        DOUBLE PRECISION,
    packet_rate         DOUBLE PRECISION,
    mean_packet_size    DOUBLE PRECISION,
    packet_count        INTEGER,
    acknowledged        INTEGER NOT NULL DEFAULT 0,
        CONSTRAINT chk_alert_ack CHECK (acknowledged IN (0, 1)),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    
    -- Idempotency constraint: An alert maps uniquely to a scored window
    CONSTRAINT uq_live_alerts_window UNIQUE (window_id)
);

COMMENT ON TABLE live_alerts IS 'Statistical anomaly alerts generated by the unsupervised Dual Isolation Forest.';

CREATE INDEX IF NOT EXISTS idx_alerts_run 
    ON live_alerts(run_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_alerts_ack 
    ON live_alerts(run_id, acknowledged);

